#include "zf_common_headfile.h"
#include "foc.h"
#include "foc_config.h"
#include "foc_console.h"
#pragma section all "cpu0_dsram"

int core0_main(void)
{
    /* Preload EN low BEFORE changing its GPIO direction or initializing clocks.
     * MCU-reset behavior still needs hardware verification; firmware cannot
     * guarantee it. DRV EN inputs have internal pull-downs (R4 is series).
     */
    IfxPort_setPinLow(get_port(FOC_EN_PIN), (uint8)((unsigned int)FOC_EN_PIN & 31u));
    gpio_init(FOC_EN_PIN, GPO, GPIO_LOW, GPO_PUSH_PULL);
    clock_init();
    foc_init();
    debug_init();
    pit_init(CCU60_CH0, FOC_CONTROL_PERIOD_US);
    cpu_wait_event_ready();
    foc_console_init();
    while (TRUE) {
        foc_console_poll();
    }
}
#pragma section all restore
